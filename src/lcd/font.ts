// Throws for a character the font lacks: drawing one is a programmer error.
export function glyphRows(character: string): readonly string[] {
  const rows = GLYPHS[character];
  if (rows === undefined) {
    throw new Error(
      `The LCD font has no glyph for ${JSON.stringify(character)}`,
    );
  }
  return rows;
}
